/**
 * Scales a landslide hazard polygon toward its natural centroid.
 * Reduces the footprint by 30% to fit tightly on mountain slopes without overshooting
 * across the valley floor, village settlements, and riverbed.
 */
function scaleLandslidePolygon(polygon: [number, number][], factor: number = 0.70): [number, number][] {
  const centerLat = polygon.reduce((sum, p) => sum + p[0], 0) / polygon.length;
  const centerLng = polygon.reduce((sum, p) => sum + p[1], 0) / polygon.length;
  return polygon.map(([lat, lng]) => [
    Number((centerLat + (lat - centerLat) * factor).toFixed(5)),
    Number((centerLng + (lng - centerLng) * factor).toFixed(5)),
  ]);
}

